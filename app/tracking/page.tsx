type TripStatus =
  | 'driver_on_way'
  | 'driver_arrived'
  | 'in_progress'
  | 'pending_payment'
  | 'completed'
  | 'canceled';

function mapRemoteStatus(status: string | null | undefined): TripStatus | null {
  if (!status) return null;
  switch (status.toLowerCase()) {
    case 'requested':
    case 'driver_offered':
    case 'accepted':
    case 'driver_on_way':
    case 'driver_on_route':
      return 'driver_on_way';
    case 'driver_arrived':
      return 'driver_arrived';
    case 'in_progress':
      return 'in_progress';
    case 'pending_payment':
    case 'pending_rating':
      return 'pending_payment';
    case 'rating_completed':
    case 'completed':
      return 'completed';
    case 'canceled':
      return 'canceled';
    default:
      return null;
  }
}

